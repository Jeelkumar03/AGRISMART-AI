export function getLang() {
  return localStorage.getItem("agrismart:lang") || "en";
}

export function setLang(lang) {
  localStorage.setItem("agrismart:lang", lang);
}

/** Translate a key, with optional {placeholder} interpolation. */
export function t(key, params = {}) {
  const lang = getLang();
  let str = (dict[lang] && dict[lang][key]) || dict.en[key] || key;
  Object.entries(params).forEach(([k, v]) => {
    str = str.replace(new RegExp(`{${k}}`, "g"), v);
  });
  return str;
}

/** Applies data-i18n / data-i18n-placeholder attributes found under `root`. */
export function applyTranslations(root = document) {
  document.documentElement.lang = getLang();
  root.querySelectorAll("[data-i18n]").forEach(el => {
    el.textContent = t(el.getAttribute("data-i18n"));
  });
  root.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    el.setAttribute("placeholder", t(el.getAttribute("data-i18n-placeholder")));
  });
}

/** Populates and wires up a <select> element as the language switcher. */
export function mountLanguageSwitch(selectEl) {
  Object.entries(LANGUAGES).forEach(([code, label]) => {
    const opt = document.createElement("option");
    opt.value = code;
    opt.textContent = label;
    selectEl.appendChild(opt);
  });
  selectEl.value = getLang();
  selectEl.addEventListener("change", () => {
    setLang(selectEl.value);
    applyTranslations();
    document.dispatchEvent(new CustomEvent("agrismart:langchange"));
  });
}
